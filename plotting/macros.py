r"""The number macros of the paper's text and tables, computed from the stored results.

Certified bounds are rounded outward (`display.lo`, `display.hi`); estimates, parameters and counts
are printed to significant digits (`display.pct`). `compute` groups the macros by the part of the
paper that prints them; `write_tex` writes each macro once as a \newcommand for the manuscript.
"""
import math
from collections import namedtuple
from fractions import Fraction

import data
from display import hi, lo, pct, sci

Macro = namedtuple('Macro', 'name value what source')

HEADER = '% Generated by plotting/paper.py from results/; do not edit.'

# The screen settings (N, rho, d) of the limitations paragraph.
LOW, MID, HIGH = (2, '1/20', '2'), (4, '1/2', '4'), (2, '7/10', '3')


def _exclusion(res):
    grid = res.core()
    # L_LP at N = 4, d = 2 and the 1 % target, by (profile, load)
    grid_bound = {(r['profile'], r['rho']): data.bound(r) for r in grid if r['n'] == '4' and r['d'] == '2'}
    high = [grid_bound[(p, '9/10')] for p in data.PROFILES]
    moments = {r['profile']: r for r in res.brackets(data.MOMENTS)}
    gamma, pareto = moments['gamma'], moments['pareto']
    # The witness of the combination-only certificate uses a single window row (window length ell, all
    # N classes). With every class at its target eps, that row forces at least
    #     (N (1 - e^{-lbar}) - 1 + e^{-N lbar} - N lbar eps) / ell
    # reconfigurations per unit time, where lbar = lambda (ell - d)^+ counts the arrivals of one class
    # in the window that must be served within it.
    cert = res.certificate(data.CERTIFICATE)
    certificate = f'{data.CERTIFICATES}/{data.CERTIFICATE}.json'
    witness = cert['full_level']['feasibility']['witness']
    window_rows = [w for w in witness if w['row'].startswith('window[')]
    assert len(window_rows) == 1
    ell = float(window_rows[0]['row'].split('h=')[1].split(' ')[0])
    lam, d = Fraction(cert['model']['lambda'][0]), Fraction(cert['model']['deadlines'][0])
    lam_bar = lam * max(ell - d, 0)
    n = cert['model']['n']
    rhs = n * (1 - math.exp(-lam_bar)) - 1 + math.exp(-n * lam_bar)
    nu_req = (rhs - n * lam_bar * Fraction(cert['model']['epsilon'][0])) / ell
    levels = {level['level']: level for level in cert['levels']}
    combo = [r for r in grid if data.excluded(r) and not data.excluded(r, 'base_windows')
             and not data.excluded(r, 'base_phases')]
    return [
        Macro('refMapBoundTenTnorm', lo(grid_bound[('tnorm', '1/10')], decimals=2),
              'L_LP [%], truncated normal, N = 4, ρ = 0.1, d = 2', data.GRID),
        Macro('refMapBoundTenPareto', lo(grid_bound[('pareto', '1/10')], decimals=2),
              'L_LP [%], Pareto, N = 4, ρ = 0.1, d = 2', data.GRID),
        Macro('refMomGammaUzeroUp', hi(gamma['u_simple_q'], 3), 'U_0 [%], gamma, N = 4, ρ = 1/4000, d = 15/8',
              f'{data.MOMENTS}/bracket.json'),
        Macro('refMomParetoLsafe', lo(pareto['safe_q'], 4), 'L_safe [%], Pareto, N = 4, ρ = 1/4000, d = 15/8',
              f'{data.MOMENTS}/bracket.json'),
        Macro('refMapBoundNinety', lo(min(high), decimals=1),
              'L_LP [%] of all six distributions, N = 4, ρ = 0.9, d = 2', data.GRID),
        Macro('refCertNuReq', f'{nu_req:.3f}',
              'reconfiguration rate [1/s] forced by the window row of the stored certificate', certificate),
        Macro('refCertPhaseOnly', lo(100 * levels['base_phases']['lb_max'], 3),
              'L_LP [%] with the phase constraint alone, gamma, N = 4, ρ = 0.2, d = 2', certificate),
        Macro('refCertFull', lo(100 * Fraction(cert['full_level']['min_max']['certified_value']), 4),
              'L_LP [%] of the combined test, same setting', certificate),
        Macro('refImpComboCount', str(len(combo)),
              'settings excluded only by combining the constraints, 1 % target', data.GRID),
    ]


def _gap(res):
    closed_form = data.one(res.brackets(data.BENCHMARK), rho_exact='1/20', d='2')
    finite = res.brackets(data.FINITE_LOAD)
    det = data.one(finite, profile='det', n=2, rho_exact='1/10', d='2')
    sims = res.ojf_rows()
    finite_source = f'{data.FINITE_LOAD}/bracket.json'
    deviation = max(abs(t['estimate'] / t['exact_benchmark']['miss']['hi_f64'] - 1) for v in sims for t in v['tails'])
    # OJF meets target eps at deadline d exactly when rho <= 1/N - ln(1/eps)/(mu d); here N = 2, mu = 4, d = 3
    boundary = 0.5 + math.log(0.01) / 12
    return [
        Macro('refSimMaxRelDev', pct(100 * deviation, 2),
              'largest relative deviation [%] of the simulated OJF tails from the exact miss probability', data.OJF),
        Macro('refSimRunsTotal', str(sum(v['runs'] for v in sims)), 'simulated OJF runs', data.OJF),
        Macro('refFloorTwo', pct(closed_form['floor']), 'm_0(2) [%] of the closed-form case',
              f'{data.BENCHMARK}/bracket.json'),
        Macro('refFcfsBoundaryThree', f'{boundary:.4f}', 'largest load at which OJF meets the 1 % target at d = 3',
              'closed form'),
        Macro('refFinUzeroDetTwoTenTwo', hi(det['u_simple_q']), 'U_0 [%], deterministic, N = 2, ρ = 0.1, d = 2',
              finite_source),
        Macro('refFinUkDetTwoTenTwo', hi(det['u_workload_q']), 'workload bound [%], same setting', finite_source),
        Macro('refFinLsafeDetTwoTenTwo', lo(det['safe_q']), 'L_safe [%], same setting', finite_source),
        Macro('refFiniteCases', str(len(finite)), 'settings of the finite-load set', finite_source),
    ]


def _scheduling(res):
    sw = res.sweep_rows()
    cex = data.counterexample(sw)
    region = [r for r in res.region()['region'] if not r['excluded']]
    first = region[0]
    budget = next(r for r in region if r['nu_hi'] >= 1.9 - 1e-9)  # the time budget (1 - rho) / E[tau] = 1.9
    dj = res.directional()
    matrix = data.one(dj['rows'], orientation='matrix', rho='1/10', h='3/4')
    transpose = data.one(dj['rows'], orientation='transpose', rho='1/10', h='3/4')
    ivs = {(r['orientation'], r['variant']): r for r in dj['interventions']}
    upgrade = ivs[('matrix', 'service_class1_x5/4')]
    eta_lo = data.exact(upgrade['intervals'][1]['lo'])  # entry rate of configuration 1; [0] is the total rate
    lam = [Fraction(v) for v in matrix['lambda']]
    return [
        Macro('refSweepExcludedMax', pct(100 * max(r['eps_f64'] for r in sw if r['excluded'])),
              'largest excluded target [%]', data.SWEEP),
        Macro('refRegionFirstEps', pct(100 * first['eps_f64']), 'smallest target [%] with a nonempty rate range',
              data.REGION),
        Macro('refRegionFirstNuLo', lo(first['nu_lo'], decimals=3), 'its lower end of the total reconfiguration rate',
              data.REGION),
        Macro('refRegionFirstNuHi', hi(first['nu_hi'], decimals=3), 'its upper end', data.REGION),
        Macro('refRegionBudgetEps', pct(100 * budget['eps_f64']),
              'smallest target [%] whose upper rate reaches the time-budget bound', data.REGION),
        Macro('refSweepFeasibleMin', pct(100 * min(r['eps_f64'] for r in sw if r['verdict'] == 'certified_feasible')),
              'smallest certified feasible target [%]', data.SWEEP),
        Macro('refCexEps', pct(100 * cex['eps_f64']), 'target [%] of the rate-membership counterexample', data.SWEEP),
        Macro('refEtaReference', f'{sw[0]["reference_rates"]["eta"]["f64"]:g}',
              'reconfiguration rate ν_12 = ν_21 of OJF [1/s]', data.SWEEP),
        Macro('refCexZ', f'{cex["reference_rates"]["z"]["hi_f64"]:g}', 'idle fraction z_1 = z_2 of OJF', data.SWEEP),
        Macro('refCexMf', pct(100 * cex['bracket']['u_plus']['f64']), 'exact miss probability [%] of OJF',
              data.SWEEP),
        Macro('refDirPairs', str(len(dj['comparison'])), 'direction pairs compared', data.DIRECTIONAL),
        Macro('refDirClassTwoMatrixA', lo(100 * matrix['class_bounds'][1]),
              'class-2 bound [%], E[τ_12] < E[τ_21], ρ = 0.1, h = 0.75', data.DIRECTIONAL),
        Macro('refDirClassTwoTransposeA', lo(100 * transpose['class_bounds'][1]),
              'class-2 bound [%], E[τ_12] > E[τ_21], same setting', data.DIRECTIONAL),
        Macro('refDirKappaMatrixA', lo(matrix['kappa_lower'], 3), 'κ_L, E[τ_12] < E[τ_21], same setting',
              data.DIRECTIONAL),
        Macro('refDirKappaTransposeA', lo(transpose['kappa_lower'], 3), 'κ_L, E[τ_12] > E[τ_21], same setting',
              data.DIRECTIONAL),
        Macro('refIvMatSvcAKappa', lo(upgrade['kappa_lower'], 3),
              'κ_L with μ_1 × 1.25, E[τ_12] < E[τ_21]', data.DIRECTIONAL),
        Macro('refIvTrSvcAKappa', lo(ivs[('transpose', 'service_class1_x5/4')]['kappa_lower'], 3),
              'κ_L with μ_1 × 1.25, E[τ_12] > E[τ_21]', data.DIRECTIONAL),
        Macro('refIvMatSvcAEtaLoOne', lo(eta_lo, decimals=3),
              'lowest rate [1/s] of reconfiguration into configuration 1, μ_1 × 1.25, E[τ_12] < E[τ_21]',
              data.DIRECTIONAL),
        Macro('refIvMatSvcABetaHiOne', hi(lam[0] / Fraction(eta_lo), 3),
              'most class-1 jobs served per visit on average, same setting', data.DIRECTIONAL),
    ]


def _limits(res):
    envs, seeds = res.screen()
    source = data.SCREEN_FILES

    def at(key, profile):
        """(certified bound, EC estimate) of a screen setting, as printed."""
        e = [e for e in envs if data.setting(e) == key and e['profile'] == profile][0]
        ec = {p['policy']: data.worst(p) for p in e['policies']}['ec']
        return lo(data.env_bound(e)), pct(ec)

    low_exp, low_gamma, mid_gamma, high_exp = at(LOW, 'exp'), at(LOW, 'gamma'), at(MID, 'gamma'), at(HIGH, 'exp')
    pairs = data.pairs(envs)
    return [
        Macro('refLimEcLowExp', low_exp[1], 'EC worst-class miss probability [%], exponential, (2, 0.05, 2)', source),
        Macro('refLimEcLowGamma', low_gamma[1], 'EC [%], gamma, (2, 0.05, 2)', source),
        Macro('refLimBoundLowExp', low_exp[0], 'certified bound [%], exponential, (2, 0.05, 2)', source),
        Macro('refLimBoundLowGamma', low_gamma[0], 'certified bound [%], gamma, (2, 0.05, 2)', source),
        Macro('refLimBoundMidGamma', mid_gamma[0], 'certified bound [%], gamma, (4, 0.5, 4)', source),
        Macro('refLimBoundHighExp', high_exp[0], 'certified bound [%], exponential, (2, 0.7, 3)', source),
        Macro('refLimEcMidGamma', mid_gamma[1], 'EC [%], gamma, (4, 0.5, 4)', source),
        Macro('refLimEcHighExp', high_exp[1], 'EC [%], exponential, (2, 0.7, 3)', source),
        Macro('refScreenRuns', str(len(pairs) * seeds), 'simulation runs of EC and HOL-BMW', source),
        Macro('refScreenPairs', str(len(pairs)), 'policy-setting pairs', source),
    ]


def _cost(res):
    rows = res.brackets(data.BENCHMARK) + res.brackets(data.LIGHT_LOAD) + res.brackets(data.FINITE_LOAD)
    below = sorted({r['rho'] for r in rows if r['lp'] < r['floor'] - 1e-12})
    source = 'bracket/{benchmark,light_load,finite_load}/bracket.json'
    return [
        Macro('refBracketRowsTotal', str(len(rows)), 'settings of the benchmark, light-load and finite-load sets',
              source),
        Macro('refLlpBelowFloorMaxLoad', f'{max(below, default=0):g}',
              'largest load at which L_LP falls below the lower enclosure of m_0', source),
    ]


def _workload(res):
    loss = [100 * (r['bracket']['u_workload']['u_k_plus']['f64'] - r['bracket']['benchmark']['miss']['hi_f64'])
            for r in res.bracket_rows(data.BENCHMARK)]
    refine = {(r['profile'], step): data.bracket_numbers(r) for step, rows in res.refinement().items() for r in rows}
    steps = sorted({step for _, step in refine})
    coarse, fine = steps[0], steps[-1]
    tag = {500: 'FiveHundred', 8000: 'EightThousand'}
    refine_source = f'{data.REFINEMENT}/step_{{{coarse},{fine}}}/bracket.json'
    finite = res.brackets(data.FINITE_LOAD)
    finite_source = f'{data.FINITE_LOAD}/bracket.json'

    def verdict_loads(profile, n, d, verdict):
        return [r['rho'] for r in finite if r['profile'] == profile and r['n'] == n and r['d'] == d
                and r['verdict'] == verdict]

    out = [
        Macro('refWorkloadVsExactMax', pct(max(loss), 2),
              'largest excess [pp] of the workload bound over the exact OJF miss probability, closed-form case',
              f'{data.BENCHMARK}/bracket.json'),
        Macro('refRefineStepCoarse', str(coarse), 'coarsest grid of the refinement, g = 1/S', refine_source),
        Macro('refRefineStepFine', str(fine), 'finest grid of the refinement, g = 1/S', refine_source),
        Macro(f'refRefineDetLo{tag[coarse]}', lo(refine[('det', coarse)]['u_minus_q']),
              'U^- [%], deterministic, N = 2, ρ = 0.1, d = 2, coarsest grid', refine_source),
        Macro(f'refRefineDetHi{tag[coarse]}', hi(refine[('det', coarse)]['u_workload_q']),
              'U^+ [%], same setting, coarsest grid', refine_source),
        Macro(f'refRefineDetLo{tag[fine]}', lo(refine[('det', fine)]['u_minus_q']),
              'U^- [%], same setting, finest grid', refine_source),
        Macro(f'refRefineDetHi{tag[fine]}', hi(refine[('det', fine)]['u_workload_q']),
              'U^+ [%], same setting, finest grid', refine_source),
        Macro('refFiniteCases', str(len(finite)), 'settings of the finite-load set', finite_source),
        Macro('refFiniteFeasible', str(sum(r['verdict'] == 'certified_feasible' for r in finite)),
              'certified feasible settings of the finite-load set', finite_source),
        Macro('refFiniteInfeasible', str(sum(r['verdict'] == 'certified_infeasible' for r in finite)),
              'certified infeasible settings of the finite-load set', finite_source),
        Macro('refFinFeasMaxGammaFourThree', f'{max(verdict_loads("gamma", 4, "3", "certified_feasible")):g}',
              'largest certified feasible load, gamma, N = 4, d = 3', finite_source),
        Macro('refFinInfeasMinParetoTwoThree',
              f'{min(verdict_loads("pareto_heavy", 2, "3", "certified_infeasible")):g}',
              'smallest certified infeasible load, Pareto-3/2, N = 2, d = 3', finite_source),
    ]
    # the enclosure table: N = 2, d = 2, three loads, deterministic and gamma
    for p, pt in (('det', 'Det'), ('gamma', 'Gamma')):
        for rho, rt in (('1/100', 'One'), ('1/10', 'Ten'), ('3/10', 'ThreeTenths')):
            r = data.one(finite, profile=p, n=2, d='2', rho_exact=rho)
            where = f'{p}, ρ = {data.q(rho):g}'
            out += [Macro(f'refEnc{pt}{rt}Lsafe', lo(r['safe_q']), f'L_safe [%], {where}', finite_source),
                    Macro(f'refEnc{pt}{rt}Uminus', lo(r['u_minus_q']), f'U^- [%], {where}', finite_source),
                    Macro(f'refEnc{pt}{rt}Uplus', hi(r['u_workload_q']), f'U^+ [%], {where}', finite_source),
                    Macro(f'refEnc{pt}{rt}Trunc', sci(100 * r['truncation']),
                          f'omitted probability ρ_F^(K+1) [points], {where}', finite_source),
                    Macro(f'refEnc{pt}{rt}Width', hi(r['num_width'], 2),
                          f'numerical width C^+ - C^- [points], {where}', finite_source)]
    return out


def compute(res):
    """{part of the paper: [Macro]} in the order the paper prints them."""
    return {'exclusion': _exclusion(res), 'gap': _gap(res), 'scheduling': _scheduling(res),
            'limits': _limits(res), 'cost': _cost(res), 'workload': _workload(res)}


def unique(sections):
    """Each macro once, in the order of first appearance; a macro printed in two parts must agree."""
    out = {}
    for macros in sections.values():
        for m in macros:
            assert out.setdefault(m.name, m).value == m.value, m.name
    return list(out.values())


def write_tex(path, sections):
    lines = [HEADER] + [f'\\newcommand{{\\{m.name}}}{{{m.value}}}' for m in unique(sections)]
    path.write_text('\n'.join(lines) + '\n')
